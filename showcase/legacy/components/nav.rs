/// Rappresenta la registrazione centrale e unificata di un componente o elemento nello Showcase.
/// Aggiungendo un elemento a `COMPONENTS`, esso viene automaticamente propagato a:
/// 1. Ricerca globale (`SearchPalette` / `CommandPalette`, Ctrl+K)
/// 2. Barra laterale (`SidebarView`), raggruppato nella corretta sezione/categoria
/// 3. Elenco dinamico delle feature Cargo (`all_cargo_features()`)
#[derive(Clone, PartialEq, Debug)]
pub struct ComponentItem {
    /// Nome del componente/elemento visualizzato nella barra laterale e nella ricerca.
    pub name: &'static str,
    /// Rotta Dioxus associata alla pagina di documentazione del componente.
    pub route: Route,
    /// Elenco degli URL o percorsi di navigazione associati al componente.
    pub urls: &'static [&'static str],
    /// Categoria o classe tematica del componente (es. "Inserimento & Form", "Layout & Struttura").
    pub class: &'static str,
    /// Feature flag Cargo richieste o associate al componente nel crate `shadow-design`.
    pub features: &'static [&'static str],
    /// Icona SVG nativa utilizzata nei link di navigazione e nella palette di ricerca.
    pub icon: IconKind,
    /// Descrizione sintetica del componente per i risultati di ricerca.
    pub description: &'static str,
    /// Parole chiave per facilitare la ricerca nella CommandPalette.
    pub keywords: &'static str,
}

/// Alias per compatibilità con l'interfaccia di navigazione esistente.
#[allow(dead_code)]
pub type ComponentNavEntry = ComponentItem;

/// Categoria tematica per il raggruppamento dei componenti nella barra laterale.
#[derive(Clone, Copy, PartialEq, Debug)]
pub struct ComponentCategory {
    pub name: &'static str,
    pub icon: IconKind,
    pub is_accent: bool,
}

