/// Restituisce l'elenco ordinato e deduplicato di tutte le feature Cargo
/// derivate automaticamente da tutti gli elementi registrati.
pub fn all_cargo_features() -> Vec<&'static str> {
    let mut feats = std::collections::BTreeSet::new();
    for comp in COMPONENTS {
        for feat in comp.features {
            feats.insert(*feat);
        }
    }
    feats.insert("all");
    feats.insert("theme");
    feats.into_iter().collect()
}

#[component]
pub fn SearchPalette(mut is_open: Signal<bool>) -> Element {
    let nav = use_navigator();

    let actions: Vec<CommandAction> = COMPONENTS
        .iter()
        .map(|comp| {
            let mut act = CommandAction::new(comp.name, comp.name)
                .with_description(comp.description)
                .with_category(comp.class)
                .with_icon(comp.icon);
            let kws: Vec<&str> = comp.keywords.split_whitespace().collect();
            act = act.with_keywords(kws);
            act
        })
        .collect();

    rsx! {
        CommandPalette {
            opened: is_open,
            actions: actions,
            placeholder: "Cerca componenti o naviga... (Ctrl+K)".to_string(),
            on_select: move |action: CommandAction| {
                if let Some(comp) = COMPONENTS.iter().find(|c| c.name == action.id) {
                    nav.push(comp.route.clone());
                }
            },
        }
    }
}
